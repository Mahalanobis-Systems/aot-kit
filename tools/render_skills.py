#!/usr/bin/env python3
"""Generate the skills, catalog.yaml and the optimization lists from library/.

    render_skills.py           write everything that is out of date
    render_skills.py --check   write nothing; exit 1 if anything is out of date (CI runs this)

What it writes:
- skills/<slug>/SKILL.md: the frontmatter and the part between the generated markers. Everything
  after the end marker is written by hand and kept as it is. A skill is a placeholder while that
  hand-written part still has its "## To build" checklist; take the checklist out when the skill
  is built, and the placeholder banner and the word "Placeholder." go with it.
- catalog.yaml: rebuilt in full.
- README.md and skills/start/SKILL.md: the optimization lists between their markers.

A new entry gets a new skill with the To build checklist. A skill with no entry is an error.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "library"
SKILLS = ROOT / "skills"

BEGIN = "<!-- Generated from library/entries/{slug}.yaml by tools/render_skills.py. Edit the entry, not this part. -->"
END = "<!-- End of the generated part. Everything below is written by hand. -->"
LIST_BEGIN = "<!-- optimizations: generated by tools/render_skills.py -->"
LIST_END = "<!-- end optimizations -->"
TO_BUILD = """## To build

This skill is a placeholder. To make it usable on a client's agent:
- [ ] **Detect:** a check that finds where this applies, from the agent's code, its traces and
      its eval results (the signals above), and says how strongly.
- [ ] **Apply:** a step-by-step procedure for making the change in the client's repository,
      with the decisions the owner must make.
- [ ] **Measure:** the before/after recipe at this tier's evidence gate, run through
      aot-evals (`aot-evals:run` for a paired comparison).
- [ ] **Evidence:** a short, dated summary of what the change has done elsewhere, with the
      conditions under which it helped or hurt.
"""
# One line per tier for the README and the start skill; vocabulary.yaml holds the full definitions.
TIER_BLURB = {
    1: "no-regret changes that cannot alter what the model sees; checked by exact replay or ~10 hand-labeled examples.",
    2: "remove hard failures (crashes, loops, timeouts, injection); measured as failure rate before and after.",
    3: "real trade-offs within the existing design; needs the calibrated quality eval and a paired comparison.",
    4: "change the agent's structure; needs production cost baselines and an A/B or blue/green test.",
}
PROPOSED_NOTE = "¹ Tier proposed: the pattern library carries no tier, so these are a first assignment."


def clip(text: str, n: int) -> str:
    text = " ".join(str(text).split())
    if len(text) <= n:
        return text
    return text[:n].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def steps(how: str) -> str:
    parts = re.split(r"(?:^|\s)(\d)\. ", how.strip())
    if len(parts) < 3:
        return how.strip()
    return "\n".join(f"{parts[i]}. {parts[i + 1].strip()}" for i in range(1, len(parts) - 1, 2))


def order(e: dict) -> tuple:
    """The kit's order: techniques, then patterns, each by legacy id; entries added after the
    2026-10-19 renumbering have no legacy id and follow, by id."""
    legacy = e.get("legacy_id")
    return (legacy is None, e["kind"] != "technique", int(legacy[1:]) if legacy else 0, e["id"])


def load() -> tuple[list[dict], dict, dict]:
    es = [yaml.safe_load(p.read_text()) for p in sorted((LIB / "entries").glob("*.yaml"))]
    vocab = yaml.safe_load((LIB / "vocabulary.yaml").read_text())
    excluded = yaml.safe_load((LIB / "excluded.yaml").read_text())
    return sorted(es, key=order), vocab, excluded


def generated(e: dict, by_id: dict, vocab: dict, placeholder: bool) -> tuple[str, str]:
    """The skill's frontmatter and its generated part."""
    tiers = {t["tier"]: t for t in vocab["tiers"]}
    cat_names = {i["id"]: f"{c['name']}: {i['name']}" for c in vocab["categories"] for i in c["items"]}
    t = e["tiers"][0]
    tier_name = tiers[t["tier"]]["name"]
    proposed = t.get("proposed")
    signals = e["detect"].get("traces") or e["detect"].get("static", "")
    desc = (
        f"AOT optimization {e['id']} (Tier {t['tier']}, {tier_name}): {e['name']}."
        + (" Placeholder." if placeholder else "")
        + f" Use when an agent shows: {signals.rstrip('.')}."
    )
    front = "\n".join([
        "---",
        f"name: {e['slug']}",
        "description: " + yaml.safe_dump(desc, width=10**6, default_style='"').strip(),
        "---",
    ])
    prov = e["provenance"]
    change = f"{prov['change_type']} / {prov['sub_type']}" + (f" ({prov['action']})" if prov.get("action") else "")
    legacy = e.get("legacy_id") or "none (added after 2026-10-19)"
    if prov.get("library_group"):
        legacy += f" ({prov['library_group']}, from the {prov.get('library_source', 'master')} cookbook)"
    rows = [
        ("Id", e["id"]),
        ("Earlier id", legacy),
        ("Tier (proposed)" if proposed else "Tier", f"{t['tier']} ({tier_name}): {t['why']}"),
        ("Categories", "; ".join(cat_names[c] for c in e["categories"]) or "none yet"),
        ("Change", change),
    ]
    if e.get("absorbs"):
        rows.append(("Also covers", "; ".join(a["name"] for a in e["absorbs"])))
    out = [BEGIN.format(slug=e["slug"]), "", f"# {e['name']}", ""]
    if placeholder:
        out += [
            f"> **Placeholder.** Generated from `library/entries/{e['slug']}.yaml` (entry {e['id']}). It",
            "> describes the optimization; it does not yet walk an agent through applying it."
            + (" The tier is proposed." if proposed else "")
            + " See **To build** below.",
            "",
        ]
    out += [
        "| | |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in rows],
        "",
        "## What it is",
        "",
        e["summary"].strip(),
        "",
        "## When it applies",
        "",
    ]
    d = e["detect"]
    for key, label in [("static", "In the code"), ("traces", "In traces"), ("evals", "In eval results")]:
        if d.get(key):
            out.append(f"- **{label}:** {d[key]}")
    if d.get("judge"):
        out.append(f"- **Judge:** {d['judge']}")
    if d.get("probes"):
        out.append(f"- **Probes:** {d['probes']['what']}")
    out += ["", "## How (outline)", ""]
    out.append(steps(e["how"]) if e.get("how") else "To be written: the entry names the change but not the steps.")
    out += ["", "## How to measure", ""]
    if e.get("measure"):
        for m in e["measure"]:
            tier = f" (Tier {m['tier']})" if m.get("tier") else ""
            out.append(f"- **{m['method']}**{tier}: {m['how']}")
    elif e.get("assessment"):
        qa = e["assessment"]["qa"]
        for key in ("unit", "examples", "benchmark", "production"):
            if qa.get(key):
                out.append(f"- **{key.capitalize()}:** {qa[key]}")
    rated = {k: v for k, v in e["impact"].items() if k != "primary" and v["effect"] != "unknown"}
    assessed = all(v.get("basis") == "assessment" for v in rated.values())
    out += ["", "## Expected impact" + (" (first-pass assessment, unmeasured)" if assessed else ""), ""]
    for key, v in rated.items():
        bits = ", ".join(x for x in (v["effect"], v.get("size")) if x)
        basis = " (unmeasured)" if v.get("basis") == "assessment" and not assessed else ""
        when = f": {v['when']}" if v.get("when") else ""
        out.append(f"- **{key.capitalize()}:** {bits}{basis}{when}")
    ev = e.get("evidence") or []
    if ev:
        out += ["", "## Evidence (summary)", ""]
        for r in ev[:5]:
            date = f" ({r['date']})" if r.get("date") else ""
            out.append(f"- {clip(r['source'], 140)}{date}: {clip(r['effect'], 240)}")
        if len(ev) > 5:
            out.append(f"- …and {len(ev) - 5} more sources in `library/entries/{e['slug']}.yaml`.")
    if e.get("caveats"):
        # "[from T08]" marks a caveat inherited from a retired entry; the skill leaves it out.
        out += ["", "## Caveats", "", re.sub(r"\[from [TP]\d{2}\]\s*", "", e["caveats"]).strip()]
    related = []
    back = [x["id"] for x in by_id.values() if e["id"] in x.get("related", [])]
    for rid in dict.fromkeys(e.get("related", []) + back):
        if rid in by_id and rid != e["id"]:
            r = by_id[rid]
            related.append(f"- `aot-kit:{r['slug']}` ({rid}, {r['name']})")
    if related:
        out += ["", "## Related", "", *related]
    out += ["", END]
    return front, "\n".join(out)


def skill(e: dict, by_id: dict, vocab: dict, current: str | None) -> str:
    if current is None:
        hand = TO_BUILD
    elif END in current:
        hand = current.split(END, 1)[1].lstrip("\n")
    elif "\n## To build\n" in current:  # a skill from before the generated markers
        hand = current[current.index("\n## To build\n") + 1 :]
    else:
        raise SystemExit(
            f"skills/{e['slug']}/SKILL.md: no end marker or To build section; can't tell what is hand-written"
        )
    front, body = generated(e, by_id, vocab, placeholder="## To build" in hand)
    return f"{front}\n\n{body}\n\n{hand}"


def catalog(es: list[dict], excluded: dict) -> str:
    folded = sorted(
        (
            {"legacy_id": a["legacy_id"], "name": a["name"], "covered_by": e["id"]}
            for e in es
            for a in e.get("absorbs", [])
        ),
        key=lambda f: int(f["legacy_id"][1:]),
    )
    gone = [{"legacy_id": x["id"], "name": x["name"], "why": x["why"]} for x in excluded["excluded"]]
    gone += [
        {"legacy_id": x["entry"]["id"], "name": x["entry"]["name"], "why": x["reason"]}
        for x in excluded.get("archived", [])
    ]
    rows = []
    for e in es:
        row = {"id": e["id"]}
        if e.get("legacy_id"):
            row["legacy_id"] = e["legacy_id"]
        row |= {"skill": e["slug"], "name": e["name"], "kind": e["kind"], "tier": e["tiers"][0]["tier"]}
        if e["tiers"][0].get("proposed"):
            row["tier_proposed"] = True
        row["categories"] = e["categories"]
        row["absorbs"] = [a["legacy_id"] for a in e.get("absorbs", [])]
        rows.append(row)
    doc = {
        "counts": {
            "skills": len(es),
            "techniques": sum(e["kind"] == "technique" for e in es),
            "patterns": sum(e["kind"] == "pattern" for e in es),
            "patterns_folded": len(folded),
            "patterns_optimizer_side": sum(g["legacy_id"].startswith("P") for g in gone),
        },
        "optimizations": rows,
        "folded_patterns": folded,
        "excluded": gone,
    }
    head = (
        "# Every optimization aot-kit has a skill for, one row per skill. Generated from library/ by\n"
        "# tools/render_skills.py: change the entry in library/entries/, not this file.\n"
        "# `absorbs` lists library patterns that are the same change as the entry and have no skill of\n"
        "# their own; `folded_patterns` is the same mapping the other way round. `excluded` lists ids that\n"
        "# are not optimizations of an agent, or were dropped in review.\n\n"
    )
    return head + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)


def by_tier(es: list[dict]) -> dict[int, list[dict]]:
    out: dict[int, list[dict]] = {t: [] for t in TIER_BLURB}
    for e in es:
        out[e["tiers"][0]["tier"]].append(e)
    return out


def readme_list(es: list[dict], vocab: dict) -> str:
    names = {t["tier"]: t["name"] for t in vocab["tiers"]}
    out = [PROPOSED_NOTE, ""]
    for tier, group in by_tier(es).items():
        blurb = TIER_BLURB[tier]
        out += [f"### Tier {tier}: {names[tier]}", "", blurb[0].upper() + blurb[1:], ""]
        out += ["| Skill | Number | Optimization | Covers |", "|---|---|---|---|"]
        for e in group:
            mark = " ¹" if e["tiers"][0].get("proposed") else ""
            covers = ", ".join(a["legacy_id"] for a in e.get("absorbs", []))
            out.append(f"| `{e['slug']}` | {e['id']}{mark} | {e['name']} | {covers} |")
        out.append("")
    return "\n".join(out).rstrip("\n")


def start_list(es: list[dict], vocab: dict) -> str:
    names = {t["tier"]: t["name"] for t in vocab["tiers"]}
    out = []
    for tier, group in by_tier(es).items():
        out += [f"**Tier {tier}, {names[tier]}:** {TIER_BLURB[tier]}", ""]
        out += [f"- `{e['slug']}` ({e['id']}): {e['name']}" for e in group]
        out.append("")
    return "\n".join(out).rstrip("\n")


def splice(path: Path, text: str, body: str) -> str:
    if LIST_BEGIN not in text or LIST_END not in text:
        raise SystemExit(f"{path.relative_to(ROOT)}: missing the {LIST_BEGIN} / {LIST_END} markers")
    before, rest = text.split(LIST_BEGIN, 1)
    after = rest.split(LIST_END, 1)[1]
    return f"{before}{LIST_BEGIN}\n{body}\n{LIST_END}{after}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if anything is out of date")
    args = ap.parse_args()
    es, vocab, excluded = load()
    by_id = {e["id"]: e for e in es}

    want: dict[Path, str] = {}
    for e in es:
        p = SKILLS / e["slug"] / "SKILL.md"
        want[p] = skill(e, by_id, vocab, p.read_text() if p.exists() else None)
    slugs = {e["slug"] for e in es} | {"start"}
    orphans = sorted(p.name for p in SKILLS.iterdir() if p.is_dir() and p.name not in slugs)
    if orphans:
        raise SystemExit(f"skills with no library entry: {', '.join(orphans)}; rename or remove them")
    want[ROOT / "catalog.yaml"] = catalog(es, excluded)
    lists = [(ROOT / "README.md", readme_list(es, vocab)), (SKILLS / "start" / "SKILL.md", start_list(es, vocab))]
    for path, body in lists:
        want[path] = splice(path, path.read_text(), body)

    stale = [p for p, text in want.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run `make render` and commit the result", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p])
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"OK: {len(es)} skills, {len(stale)} file(s) updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
